/**
 * `.env` 를 읽어 환경변수로 올린다.
 *
 * Node 22 내장이라 의존성이 필요 없다. 파일이 없으면 그냥 넘어간다 —
 * 환경변수로 직접 주는 방식도 그대로 동작해야 한다.
 *
 * ## 왜 별도 파일인가
 *
 * `import` 보다 **먼저** 실행돼야 한다. 다른 모듈이 로드되는 시점에 이미
 * `process.env` 가 채워져 있어야, 모듈 최상단에서 키를 읽는 코드가 생겨도
 * 안전하다. 그런데 import 문 사이에 코드를 끼우면 「import 는 맨 위에」
 * 규칙에 걸린다.
 *
 * 부수 효과만 있는 모듈로 떼어 **맨 위에서 import** 하면 둘 다 지킬 수 있다.
 * ES 모듈은 import 를 선언 순서대로 평가하므로, 이 줄이 첫 번째면 이 파일이
 * 가장 먼저 돈다.
 */
try {
  process.loadEnvFile('.env');
} catch {
  // .env 가 없다. 환경변수만으로 동작한다.
}
