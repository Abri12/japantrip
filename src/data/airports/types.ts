/**
 * 공항 → 시내 이동 큐레이션 데이터.
 *
 * 이 영역만큼은 API보다 사람이 정리한 데이터가 낫다. 경로 탐색 API는
 * "어느 노선이 초행자에게 덜 헷갈리는가", "JR패스로 커버되는가" 같은
 * 판단을 못 하기 때문이다. 그래서 정적 데이터로 두고 앱에 내장한다.
 * 부수 효과로 비행기에서 내려 데이터 로밍이 안 켜진 상태에서도 열린다.
 *
 * 요금·소요시간은 2026년 8월 기준 표준 운임이다. 실제 금액은 변동하므로
 * UI에 기준 시점을 함께 노출한다.
 */

export type RouteType = 'train' | 'monorail' | 'bus' | 'taxi';

/**
 * 막차 시간.
 *
 * 여러 출처를 대조해 봐도 분 단위까지 일치하는 곳이 드물다(예: 난카이 라피트는
 * "23시 무렵"으로만 나오는 자료가 많고, 정확한 평일/주말 구분을 확인하지 못했다).
 * 그래서 확신 수준을 `confidence` 로 같이 들고 다닌다 — 틀릴 수 있는 시간을
 * 확정된 것처럼 보여주면, 그걸 믿고 나섰다가 정말로 막차를 놓치는 사람이 나온다.
 */
export interface LastTrain {
  /** HH:MM, 일본 표준시(JST) 기준 */
  time: string;
  /**
   * confirmed: 복수 출처가 분 단위까지 일치 · approx: "그 시간 전후"로만 확인됨.
   * approx 는 UI에 반드시 "약" 표시와 재확인 안내가 함께 나가야 한다.
   */
  confidence: 'confirmed' | 'approx';
}

/**
 * 시내에서 **공항으로** 가는 첫차.
 *
 * `LastTrain` 과 방향이 반대다. 막차는 늦게 도착한 사람이 시내로 들어갈 수
 * 있는지를 묻고, 첫차는 새벽 비행기를 타는 사람이 공항에 갈 수 있는지를 묻는다.
 * 같은 노선이라도 답이 다르므로 한 필드로 뭉뚱그리면 안 된다.
 *
 * 이 값이 없으면 앱은 「몇 시에 나서라」까지만 말하고 그 시각에 열차가 있는지는
 * 말하지 않는다. 새벽 6시 비행기라면 계산기가 03시대를 뱉는데, 그 시간에는
 * 어느 공항선도 다니지 않는다 — 그걸 모르고 나선 사람은 역 앞에서 알게 된다.
 */
export interface FirstTrain {
  /**
   * 어느 역에서 타는 기준인지.
   *
   * 첫차 시각은 타는 역마다 다르다. 「05:15」만 적으면 어디 기준인지 알 수 없어
   * 자기 숙소와 맞춰볼 수 없다. 그 노선에서 여행자가 가장 많이 쓰는 시내 역을
   * 기준으로 잡고 이름을 함께 적는다.
   */
  from: string;
  /** HH:MM, 일본 표준시(JST) · **평일** 기준 */
  time: string;
  confidence: 'confirmed' | 'approx';
}

/**
 * 그 노선을 타는 순서 — 비행기에서 내린 순간부터 시내에 닿을 때까지.
 *
 * 「난카이 공항급행 45분 970엔」만으로는 처음 가는 사람이 못 움직인다. 짐 찾고
 * 나와서 어느 쪽으로 걸어야 하는지, 표는 어디서 사는지, 승강장에서 무엇을 보고
 * 맞는 열차인지 확인하는지가 실제로 헤매는 지점이다.
 *
 * `signJa` 가 핵심이다. 현지에서 눈에 들어오는 건 한국어 설명이 아니라 표지판에
 * 적힌 일본어라, 그걸 그대로 들고 있어야 대조가 된다.
 */
export interface RouteStep {
  /** 이 단계에서 할 일 */
  action: string;
  /**
   * 「간략히」에서도 보여줄 단계인지 — **모르면 틀리는 지점**만 표시한다.
   *
   * 순서를 다 적으면 10단계가 되는데, 그중 대부분은 그냥 걷는 구간이다.
   * 걷는 구간은 눈앞에 길이 하나뿐이라 안 적어도 알아서 간다. 반대로
   * 「1층엔 역이 없으니 2층으로」, 「JR 말고 난카이 개찰구로」, 「特急券을
   * 따로 사야 한다」 같은 것은 모르면 그 자리에서 틀린 선택을 한다.
   *
   * 그래서 간략히는 단계를 요약하지 않고 **갈림길만 남긴다.** 요약하면
   * 문장이 뭉개져서 현장에서 못 쓰는데, 갈림길만 남기면 각 줄이 그대로
   * 쓸 수 있는 지시로 남는다.
   *
   * 아무 단계에도 표시가 없으면 간략히에서도 전부 보여준다 — 아직 고르지
   * 않은 노선이 조용히 텅 비는 것보다 낫다.
   */
  key?: boolean;
  /**
   * 지금 어디에 서 있고 어디로 움직이는지.
   *
   * 「연결통로로 건너가요」 같은 지시는 처음 온 사람에게 아무 도움이 안 된다.
   * 몇 층인지, 어느 쪽으로 걷는지, 무엇이 보이면 맞게 가고 있는 건지가 있어야
   * 실제로 발이 움직인다.
   */
  where?: string;
  /** 표지판·안내판에서 찾을 일본어 원문 */
  signJa?: string;
  /** 이 단계에 걸리는 시간 */
  minutes?: number;
  /** 여기서 자주 틀린다 */
  caution?: string;
  /**
   * 틀렸을 때 되돌리는 법.
   *
   * 초행자를 가장 불안하게 하는 건 「틀리면 어떻게 되지」다. 되돌릴 수 있다는
   * 걸 미리 알려주면, 확신이 없어도 일단 움직이게 된다.
   */
  recover?: string;
  /** 이 단계에서 돈을 낸다면 얼마를 어떻게 */
  cost?: string;
  /**
   * 글로는 설명이 안 되는 기호를 그려서 보여줘야 할 때.
   *
   * 컨택리스 마크가 그렇다 — 「))) 표시」라고 적어도 카드에서 뭘 찾아야 하는지
   * 잘 안 와닿는다. 실제 모양을 그려 두면 카드와 개찰구에서 바로 대조된다.
   */
  icon?: 'contactless';
}

/**
 * 시내에서 서는 역 하나.
 *
 * `transfer` 가 핵심이다. 역 이름만 나열하면 「거기가 어디인지」를 모르는
 * 사람에게는 글자일 뿐이라, 그 역에서 무엇으로 갈아타는지 · 무엇이 가까운지를
 * 같이 적어야 자기 숙소와 맞춰볼 수 있다.
 */
export interface RouteStop {
  name: string;
  nameJa: string;
  /** 여기서 갈아타는 노선이나, 걸어갈 수 있는 곳 */
  transfer?: string;
}

export interface TransitRoute {
  id: string;
  /** 한국어 노선명 */
  name: string;
  /** 일본어 원표기 — 현지 표지판·안내방송과 대조하는 용도다 */
  nameJa: string;
  type: RouteType;
  /** 주요 도착지 */
  destination: string;
  /**
   * 행선지의 일본어 원문.
   *
   * 역 이름보다 이쪽이 더 자주 쓰인다. 승강장에서 어느 열차를 탈지 고르는 근거가
   * **열차 전면과 전광판에 뜬 행선지**이기 때문이다. 한국어 표기만 들고 있으면
   * 눈앞의 글자와 대조할 방법이 없다.
   *
   * 난바는 한자(難波)가 아니라 なんば 로 쓴다 — 난카이의 역명 표기가 그렇다.
   * 이런 건 임의로 한자로 바꾸면 안 된다.
   */
  destinationJa?: string;
  /**
   * 시내에서 서는 주요 역.
   *
   * 예전에는 종점만 적어 뒀는데, 숙소가 그 역인 사람만 쓸 수 있는 정보였다.
   * 실제로는 신이마미야에서 JR 환상선으로 갈아타거나 텐가차야에서 지하철로
   * 빠지는 사람이 많고, **자기 숙소 근처에 서는지**가 노선을 고르는 기준이 된다.
   *
   * 같은 구간에도 정차역이 다르다 — 라피트는 8개역만 서고 공항급행은 그보다
   * 많이 선다. 그 차이를 보여주지 않으면 「더 빠른 열차」의 이유가 안 보인다.
   */
  stops?: RouteStop[];
  /**
   * `stops` 가 그 노선의 **전체 정차역**인지.
   *
   * 라피트는 공식 FAQ 가 8개역이라고 못 박아서 전부 나열할 수 있다. 반면
   * 공항급행은 12개역에 서는데, 여행자 숙소와 맞물리는 곳만 골라 담았다.
   *
   * 이 구분이 없으면 화면이 둘 다 「서는 역 N곳」으로 적어서, 공항급행이 딱
   * 그만큼만 서는 것처럼 읽힌다. 개수를 단정하는 건 전체 목록일 때만 해야 한다.
   */
  stopsComplete?: boolean;
  /**
   * ⚠ **이 노선의 시간·요금이 「어디까지」인지.** 반드시 채운다.
   *
   * 여기가 이 파일에서 가장 자주 틀리는 자리다. 노선에 `minutes: 15, yen: 330`
   * 만 적어 두면 그 숫자가 마치 **그 노선을 타면 어디든** 그만큼 걸리고 그만큼
   * 든다는 뜻으로 읽힌다. 실제로는 케이큐선이 시나가와까지 15분 330엔이고
   * 아사쿠사까지는 35분 599엔이다. 같은 노선, 다른 답이다.
   *
   * 그래서 규칙은 하나다 — **시간과 요금은 노선의 속성이 아니라
   * (노선 × 도착지)의 속성이다.** 노선에 하나만 적을 거라면 그게 어디까지인지
   * 이름을 함께 적어야 문장이 참이 된다. 화면도 이 이름을 반드시 같이 그린다.
   *
   * 고르는 기준은 **그 노선을 타는 사람이 가장 많이 내리는 역**이다. 종점이
   * 아니어도 된다 — 간쿠쾌속의 종점은 오사카역이지만 텐노지에서 내리는 사람도
   * 많고, 그 값은 `CityHub` 쪽에 따로 있다.
   *
   * `destination` 과 헷갈리지 말 것. 저건 **열차 전면에 뜨는 행선지 글자**라
   * 승강장에서 대조하는 용도고, 이건 **숫자의 기준점**이다. 둘이 같을 때가
   * 많지만 뜻이 다르므로 하나로 합치지 않는다.
   */
  fareTo: string;
  /** `fareTo` 까지 걸리는 시간 */
  minutes: number;
  /** `fareTo` 까지의 요금 */
  yen: number;
  /** 초행자에게 가장 무난한 선택 */
  recommended?: boolean;
  /** 좌석 지정이 필요한 열차인지 */
  reserved?: boolean;
  note?: string;
  /** 열차·버스에만 있다. 택시는 막차 개념이 없다 */
  lastTrain?: LastTrain;
  /** 시내 → 공항 첫차. 귀국일에 몇 시부터 움직일 수 있는지를 답한다 */
  firstTrain?: FirstTrain;
  /** 타는 순서. 조사가 끝난 노선만 채운다 — 반쯤 맞는 순서는 없느니만 못하다 */
  steps?: RouteStep[];
  /** 미리 예약할 수 있는 노선 */
  booking?: RouteBooking;
}

/** 출발 전에 좌석을 잡아둘 수 있는 노선의 예약 안내 */
export interface RouteBooking {
  /** 예약 창구 이름 */
  name: string;
  url: string;
  /** 언제부터 언제까지 살 수 있는지 */
  window: string;
  /** 예약하면 뭐가 나은지 */
  note: string;
}

/**
 * 컨택리스(터치) 결제로 탈 수 있는지.
 *
 * 한국 여행자가 가장 모르는 영역이다. 카드에 ))) 표시만 있으면 충전도 보증금도
 * 없이 그냥 타는데, 대부분 IC카드를 사러 줄을 선다.
 *
 * 다만 **사업자마다 되고 안 되고가 갈린다.** 「일본은 이제 카드로 탄다」고
 * 뭉뚱그리면 JR 개찰구에서 막힌다. 그래서 되는 곳과 안 되는 곳을 각각 이름으로
 * 적는다 — 안 되는 목록이 오히려 더 중요하다.
 */
export interface ContactlessInfo {
  /** 컨택리스로 탈 수 있는 것 */
  supported: { name: string; perk?: string }[];
  /** 안 되는 것 — 여기서 막히면 표를 사야 한다 */
  unsupported: { name: string; reason: string }[];
}

/**
 * 정기 노선표에 없는 대안 — 택시, 렌터카.
 *
 * TransitRoute 와 구조를 다르게 둔 이유: 이쪽은 "몇 분 · 얼마"가 아니라
 * "요금대"로만 말할 수 있는 것들이라(택시는 교통 상황에 따라, 렌터카는
 * 일 단위 요금이라) 억지로 같은 모양에 끼워 맞추면 숫자가 오해를 부른다.
 */
export interface OtherOption {
  id: string;
  type: 'taxi' | 'rentalcar';
  name: string;
  minutes?: number;
  yenLow: number;
  yenHigh: number;
  /** 택시는 편도 요금대, 렌터카는 1일 요금대 */
  unit: '편도' | '1일';
  note: string;
}

/**
 * 도착 거점까지 가는 한 가지 방법.
 *
 * `TransitRoute` 와 다른 물건이다. 저쪽은 **노선**을 설명하고(정차역·타는 순서·
 * 막차·컨택리스), 이쪽은 **「내 숙소까지 얼마나 걸리고 얼마냐」** 한 줄만 답한다.
 * 노선 하나가 거점마다 다른 답을 주기 때문에 따로 둘 수밖에 없다 — 케이큐는
 * 시나가와까지 15분 330엔인데 아사쿠사까지는 35분 599엔이다.
 */
export interface HubWay {
  /**
   * **공항에서 처음 타는 노선**의 id (위 `routes`).
   *
   * 갈아타는 조합도 채운다 — 「모노레일 + 오에도선」이면 `hnd-monorail` 이다.
   * 뒷구간(오에도선)은 공항 노선이 아니라 `routes` 에 없고, 있을 필요도 없다.
   * 이 값이 하는 일은 두 가지다.
   *
   * 1. 거점을 고르면 **그 거점으로 가는 노선 카드만** 위로 올린다. 아사쿠사를
   *    골랐는데 아사쿠사에 가지 않는 모노레일 카드가 그대로 있으면, 화면이
   *    질문에 답을 하다 만 셈이다.
   * 2. 같은 노선이 두 곳에서 **다른 숫자**를 말하지 않는지 확인할 수 있다.
   *
   * 어느 노선에도 걸리지 않는 방법(공항 리무진 없는 도시의 택시 등)만 비운다.
   */
  routeId?: string;
  /** 무엇을 타는지. 갈아타면 조합 전체를 적는다 */
  label: string;
  /** 이 거점까지 걸리는 시간 */
  minutes: number;
  /** 이 거점까지의 요금 */
  yen: number;
  /** 갈아타는 횟수. 0이면 직통 */
  transfers: number;
  /** 이 거점에서 초행자에게 가장 무난한 것 */
  recommended?: boolean;
  note?: string;
  /**
   * **갈아탄 뒤부터 거점에 닿을 때까지**의 순서.
   *
   * `TransitRoute.steps` 는 공항에서 그 열차에 올라타기까지만 다룬다. 거기까지만
   * 보여주면 「모노레일 + 오에도선」을 고른 사람은 하마마쓰초에서 내린 다음
   * 무엇을 해야 하는지 모른 채 남는다. 정작 헤매는 곳은 거기다.
   *
   * 갈아타는 구간이 어려운 이유는 대개 하나다 — **역 이름이 바뀐다.**
   * 하마마쓰초에서 내려 다이몬을 찾아야 하고, 히가시니혼바시에서 내려
   * 바쿠로요코야마를 찾아야 하고, JR 「札幌」에서 지하철 「さっぽろ」로
   * 건너가야 한다. 같은 자리인데 표기가 갈려서, 길을 잘못 든 줄 알고
   * 되돌아가는 사람이 나온다. 그런 지점에는 `caution` 을 붙인다.
   *
   * 환승이 없는(`transfers: 0`) 방법에는 넣지 않는다.
   */
  transferSteps?: RouteStep[];
}

/**
 * 도착 거점 — 「시내」가 한 곳이 아닌 공항을 위한 것.
 *
 * 지금까지 이 화면은 노선을 나열하고 각 노선의 종점을 알려줬다. 그건
 * **공항 쪽에서 본 그림**이다. 정작 여행자가 들고 있는 건 반대쪽 정보다 —
 * 숙소 주소 하나. 「난카이 공항급행 45분 970엔」을 읽고도 자기 숙소가 그 선
 * 위에 있는지 모르면 아무 답이 안 된다.
 *
 * 그래서 질문을 뒤집는다. 「어느 노선을 탈까」가 아니라 「어디까지 가세요」를
 * 먼저 묻고, 거기서 노선을 역산해 준다.
 *
 * 거점은 **굵직하게** 묶는다. 역 단위로 쪼개면 목록이 다시 길어져서 고르는 일
 * 자체가 일이 된다. 실제로 한국 여행자가 묵는 동네는 도시마다 두세 곳에서
 * 다섯 곳 사이다.
 *
 * 순서는 **묵는 사람이 많은 순**이다. 가나다순이나 거리순으로 두면 첫 칸이
 * 대부분의 사람과 상관없는 곳이 된다.
 *
 * ── `TransitRoute` 와 역할을 어떻게 나누나 ────────────────
 *
 * 한 화면에 둘이 같이 나오므로, 무엇을 어디서 말할지 정해 두지 않으면 같은
 * 질문에 두 번 답하고 그 답이 서로 어긋난다. 실제로 그렇게 됐었다 — 하네다
 * 화면이 케이큐선을 「15분 330엔」이라 적어 놓고, 바로 위 거점 칸에서는 같은
 * 노선을 「35분 599엔」이라 적고 있었다. 둘 다 맞는 값인데 기준이 달랐다.
 *
 * 그래서 이렇게 나눈다.
 *
 * - **거점(`CityHub`) — 「내 숙소까지 얼마나 걸리고 얼마냐」**
 *   고르고 나면 답이 나와야 하는 자리다. 방법을 비교하는 판단(가장 빠른 것,
 *   가장 싼 것, 추천)도 전부 여기서 한다. 비교가 성립하는 유일한 자리라서다 —
 *   **도착지가 같아야 시간과 요금을 견줄 수 있다.**
 *
 * - **노선(`TransitRoute`) — 「그래서 그걸 어떻게 타냐」**
 *   막차·첫차·정차역·타는 순서·예약·컨택리스처럼 **거점을 골라도 달라지지 않는**
 *   것들. 노선 카드에도 숫자가 있지만 그건 `fareTo` 라는 기준점이 이름으로 붙은
 *   값이지, 「이 노선의 시간」이 아니다.
 *
 * 그래서 「가장 빠름 / 가장 저렴」 뱃지는 **노선 카드에 붙이지 않는다.** 붙이면
 * 서로 다른 도착지끼리 견준 결과가 되어, 신주쿠에 묵는 사람에게 시나가와까지의
 * 15분을 「가장 빠름」이라 말하게 된다.
 */
export interface CityHub {
  id: string;
  /**
   * 이 거점이 곧 **어느 도시인지** (`cities.ts` 의 id). 해당하는 도시가 없으면 비운다.
   *
   * ⚠ 공항 하나가 여러 도시의 관문인 경우에 반드시 필요하다. 간사이공항은
   * 오사카와 교토가 같이 쓰는데, 두 도시의 답이 아예 다르다 —
   * 오사카는 난카이 공항급행 45분 970엔, 교토는 하루카 80분 3,640엔이다.
   * **시간이 두 배, 요금이 네 배 가까이** 벌어진다.
   *
   * 이걸 안 물어보고 `airport.routes` 에서 `recommended` 를 집으면 교토에
   * 묵는 사람에게 난바까지의 값을 답해 준다. 실제로 그랬다 — 귀국일 화면이
   * 「비행기 3시간 15분 전」이라고 말했는데 교토 기준으로는 3시간 50분이라,
   * 되돌릴 수 없는 날에 35분을 모자라게 만들고 있었다.
   *
   * 그러니 도시가 걸린 화면에서는 `airport.routes` 가 아니라 이 값으로 거점을
   * 먼저 찾는다(`hubForCity`).
   */
  cityId?: string;
  /** 「신주쿠 · 시부야」처럼 묶어서 */
  name: string;
  nameJa: string;
  /** 어떤 사람이 여기 묵는지 — 자기 숙소가 어느 거점인지 모를 때의 단서 */
  blurb: string;
  ways: HubWay[];
}

export interface Airport {
  id: string;
  /** IATA 코드 */
  code: string;
  name: string;
  nameJa: string;
  city: string;
  region: string;
  /** 지진 정보 매칭용 도도부현명 (P2PQuake의 pref 값과 같은 표기) */
  prefecture: string;
  routes: TransitRoute[];
  /**
   * 도착 거점별 안내. 「시내」가 한 곳뿐인 공항은 비워 둔다 —
   * 고를 게 하나뿐인 선택지는 화면만 늘리고 아무것도 안 알려준다.
   */
  hubs?: CityHub[];
  /** 그 공항에서만 통하는 주의사항 */
  tips: string[];
  /** 택시·렌터카처럼 정기 노선표 밖의 대안. 조사가 끝난 공항만 채운다 */
  otherOptions?: OtherOption[];
  /** 컨택리스 결제 가능 여부. 사업자별로 확인이 끝난 공항만 채운다 */
  contactless?: ContactlessInfo;
}

