/**
 * 추천 코스 — 「그래서 어떻게 도냐」에 대한 답.
 *
 * 장소를 53곳 모아 두는 것과 「오사카 2박 3일이면 이 순서로 도세요」를 주는 것은
 * 전혀 다른 물건이다. 앞은 데이터베이스고 뒤가 가이드다. 처음 가는 사람이
 * 목록에서 스스로 동선을 짜는 건 어렵고, 그 일을 대신해 주는 게 이 앱의 자리다.
 *
 * ## 설계에서 지킨 것
 *
 * **1. 동선이 실제로 맞아야 한다.** 도톤보리 → 오사카성 → 신세카이처럼 지도에서
 * 왔다 갔다 하는 순서를 넣으면 코스가 아니라 목록일 뿐이다. 같은 방향끼리 묶고,
 * 이동은 `move` 로 명시한다.
 *
 * **2. 시간을 적되 분 단위로 짜지 않는다.** 「13:00 도착」처럼 못 박으면 조금만
 * 틀어져도 코스 전체가 쓸모없어진다. 「점심 무렵」 같은 폭이 있는 표현을 쓴다.
 *
 * **3. places.ts 를 참조한다.** 장소 정보를 여기 복사하면 두 곳이 어긋난다.
 * `placeId` 만 들고 있고, 이름·가는 법·입장료는 화면에서 원본을 읽는다.
 *
 * **4. 도착일과 귀국일을 코스에 넣는다.** 여행은 공항에서 시작해 공항에서 끝나는데,
 * 대부분의 코스 안내가 「1일차 도톤보리」부터 시작해 그 두 날을 비워 둔다.
 * 실제로는 그 이틀이 가장 헤매는 날이다.
 */

export interface CourseStop {
  /** data/places.ts 의 Place id. 장소 정보는 화면에서 원본을 읽는다 */
  placeId?: string;
  /** 장소 목록에 없는 항목 (공항 이동·숙소 체크인·식사 등) */
  custom?: string;
  /** 「점심 무렵」처럼 폭이 있는 표현. 분 단위로 못 박지 않는다 */
  when: string;
  /** 여기서 다음 곳으로 어떻게 가는지 */
  move?: string;
  /** 이 순서를 이렇게 짠 이유나 요령 */
  note?: string;
  /**
   * 이 코스가 그 장소의 **유료 부분에 실제로 들어가는지**.
   *
   * 장소의 `admissionYen` 만 보고 더하면 안 된다 — 신세카이는 이 코스에서
   * 쿠시카츠를 먹으러 가는 거지 츠텐카쿠 전망대(1,000엔)에 올라가는 게 아니고,
   * 고베 기타노도 언덕길을 걷는 일정이지 이진칸 통합권(650엔)을 사는 일정이
   * 아니다. 값을 넣는 쪽이 「들어간다」고 말해야 합계가 진짜 나가는 돈이 된다.
   *
   * 반대로 우메다 스카이빌딩처럼 전망대에 올라가는 것 자체가 목적인 곳은
   * 반드시 켠다. 안 켜면 하루 합계가 2,000엔 모자라게 나간다.
   */
  pays?: boolean;
}

export interface CourseDay {
  /** 「1일차 · 도착」 */
  label: string;
  /** 그날의 성격을 한 줄로 */
  theme: string;
  stops: CourseStop[];
  /**
   * 그날 **깔고 들어가는 교통비**(엔). 코스대로 다닐 때 어차피 나가는 돈이다.
   *
   * 왜 필요한가 — 코스를 보는 사람이 다음에 묻는 것은 「그래서 하루에 얼마
   * 드냐」다. 특히 이 앱은 교통패스를 함께 다루는데, 1일권이 이득인지 아닌지는
   * **그날 교통비가 패스값을 넘는지**로 갈린다. 그 숫자가 없으면 패스 화면의
   * 「며칠 타야 본전」이 공중에 뜬다.
   *
   * 무엇이 들어가는가 — 코스에 적힌 이동과, 코스 구조상 **반드시 따라오는
   * 되돌아오는 길**이다. 나라·고베 당일치기는 갈 때만 적혀 있어도 돌아와야
   * 다음 일정이 성립하므로 왕복으로 센다. 도보 구간은 0원이고, 입장료·식비는
   * 교통비가 아니므로 넣지 않는다.
   *
   * 어떻게 구했는가 — 2026-08-18 기준 각 사업자 공시 운임이다.
   *
   *   난카이 공항급행 난바–간사이공항  970엔  (앱의 공항 노선 데이터와 같은 값)
   *   오사카메트로  1구 190 · 2구 240 · 3구 290엔  (2023-04 개정)
   *   긴테츠 오사카난바–긴테츠나라     680엔 편도
   *   한큐 오사카우메다–고베산노미야   330엔 편도
   *   후쿠오카 지하철  1구 210 · 2구 260엔  (2019-10 개정)
   *   니시테츠 텐진–다자이후           480엔 편도
   *
   * 도쿄만 **IC(스이카·파스모) 운임**이다. 다른 도시는 종이표 값을 썼는데
   * 여기만 다른 이유가 있다 — 도쿄는 IC와 종이표 값이 따로 매겨져 있고
   * (메트로 178/180 · JR 155/160 …), 한 구간에 회사가 둘씩 걸쳐 있어서
   * 종이표로는 합계가 나오지 않는다. 각 구간은 2026-08 경로 검색으로 확인했다:
   *
   *   하네다 T3–신주쿠     739엔  (모노레일 + 오에도선)
   *   신주쿠–츠키지        209엔  (마루노우치 + 히비야)
   *   츠키지–아사쿠사      209엔  (히비야 + 긴자, 우에노 환승)
   *   아사쿠사–우에노      178엔  (긴자선)
   *   우에노–아키하바라    178엔  (히비야선)
   *   아키하바라–신주쿠    220엔  (도에이 신주쿠선)
   *   신주쿠–하라주쿠      155엔  (야마노테선)
   *   시부야–하네다 T3     772엔  (야마노테선 + 모노레일)
   *   신주쿠–가마쿠라    1,034엔 편도 (쇼난신주쿠라인)
   *   에노덴 가마쿠라–가마쿠라코코마에 260엔
   *   에노덴 가마쿠라코코마에–하세   220엔
   *   에노덴 하세–가마쿠라           200엔
   *
   * 지하철 구간은 구간제라 타는 역에 따라 한 단계씩 달라질 수 있다. 그래서
   * 화면에서는 「약」을 붙여 내보낸다. 숙소 위치에 따라서도 달라지는 값이라
   * 정확한 합계를 약속하는 것 자체가 맞지 않다.
   */
  transitYen?: number;
  /** 그날 전체에 걸리는 조언 */
  tip?: string;
}

