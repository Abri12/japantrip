/**
 * 여행 준비물 기본 목록.
 *
 * 일본 여행에서 자주 빠뜨리는 것 위주로 추렸다. 옷·세면도구처럼 어느 여행이나
 * 똑같은 항목은 넣지 않는다 — 그런 건 이미 다 챙기고, 이 앱이 도울 수 있는 건
 * "일본이라서" 필요한 것들이다.
 *
 * `linkUrl` 은 확실히 맞는 공식 도메인만 넣는다. 애매한 딥링크를 넣느니
 * 링크 없이 설명만 주는 편이 낫다.
 *
 * `route` 는 앱 안의 다른 화면으로 보내는 경우다. 준비물을 훑다가 "이거 어떻게
 * 하는 거였지" 싶을 때 앱을 나가지 않고 바로 그 안내로 넘어가게 한다.
 */

export type PackingCategory = 'document' | 'money' | 'app' | 'gear';

export interface PackingItem {
  id: string;
  category: PackingCategory;
  /**
   * 항목 아이콘.
   *
   * 앱의 다른 목록은 전부 이모지 아이콘을 달고 있는데(홈·안전·관광·여행 준비)
   * 이 화면만 체크박스와 글자뿐이라 유독 밋밋했다. 13개가 세로로 이어지는
   * 목록에서 아이콘은 장식이 아니라 **어디까지 봤는지 되찾는 표시**로 쓰인다.
   */
  emoji: string;
  title: string;
  body: string;
  /** 외부 사이트·앱으로 보낼 때 */
  linkUrl?: string;
  linkLabel?: string;
  /** 앱 안의 다른 화면으로 보낼 때 (linkUrl 과 함께 쓰지 않는다) */
  route?: string;
  routeLabel?: string;
  /**
   * 모르고 가면 현지에서 곤란해지는 항목. 카드에 경고색 띠를 둘러
   * 다른 준비물과 시각적으로 구분한다.
   */
  warn?: boolean;
  /** 경고 배지에 쓸 문구. warn 이 true 일 때만 쓰인다 */
  warnLabel?: string;
}

