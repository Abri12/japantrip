/** 장소 데이터 타입. 데이터 본문은 도시별 파일에, 집계는 index.ts에 있다. */

import { TransitMode } from '../lines';

export type PlaceCategory = 'food' | 'sight';

/**
 * 이 장소가 어떤 교통패스로 커버되는지.
 *
 * 목록에서 한눈에 보이게 하려고 따로 뺐다. 예전에는 입장료 문구 안에
 * "(주유패스 포함)" 처럼 묻혀 있었는데, 그러면 패스를 살지 말지 정할 때
 * 장소를 하나씩 열어봐야 한다. 정작 그 판단은 목록에서 내리는데도.
 *
 * 조건이 제각각이라 `condition` 이 중요하다. 같은 주유패스라도 우메다는
 * 15시 전에 들어가야 하고, 츠텐카쿠는 예약권으로 교환해야 한다.
 */
export interface PassCoverage {
  /** data/transit.ts 의 TransitPass id */
  passId: string;
  /** 무조건 무료가 아닐 때의 단서 */
  condition?: string;
}

/**
 * 경로 한 줄 — 어느 역에서 무엇을 타고 어떻게 오는지.
 *
 * 예전에는 `station: '난바역 (미도스지선) 도보 5분'` 처럼 한 문자열이었다.
 * 목록에서 제목 아래 길게 깔려 읽기 나빴고, 노선 색 같은 걸 따로 꺼내 쓸 수
 * 없었다. 문자열을 정규식으로 쪼개는 방법도 안 된다 —
 * 「산노미야역 도보 15분 (오르막)」이나 「오도리역 (3개 노선 환승)」처럼
 * 괄호가 노선명이 아닌 경우가 섞여 있어서 조용히 틀린 색을 찍게 된다.
 *
 * 주 경로와 대안 경로가 **같은 형식**이어야 한다. 예전에는 대안이
 * `note: '나나쿠마선 구시다진자마에역에서는 도보 7분이에요'` 처럼 산문이었다.
 * 그러면 노선 색 점도, 역 이름의 일본어 원문도 붙일 수 없다. 위 줄에는 색과
 * 원문이 있고 아래 줄에는 없으니, 같은 종류의 정보인데 한쪽만 반쪽이 된다.
 */
export interface Route {
  /** 실제로 타는 것. 아이콘과 항목 제목이 여기서 갈린다 (data/lines.ts) */
  mode: TransitMode;
  /** 역·정류장·항구 이름. 대중교통으로 갈 수 없는 곳은 비운다 */
  station?: string;
  /**
   * 역 이름의 일본어 원문 (역 안내판 표기 그대로).
   *
   * 실제로 지하철에서 내릴 때 보게 되는 건 한글 표기가 아니라 이 표기다.
   * 한글만 있으면 안내판과 대조할 방법이 없다. 한자·가나·카타카나가 노선마다
   * 섞여 있어(ユニバーサルシティ駅는 카타카나, すすきの駅는 히라가나) 표기를
   * 임의로 통일하지 않고 그 역이 실제로 쓰는 표기를 그대로 옮긴다.
   */
  stationJa?: string;
  /** data/lines.ts 의 LINES 키. 환승역은 여러 개 */
  lineIds?: string[];
  /**
   * 노선색으로 표현할 수 없는 노선·회사 (JR·사철).
   *
   * JR 은 한 회사가 색이 다른 노선을 여러 개 굴리고, 사철은 노선색 체계가
   * 지하철만큼 일관되지 않다. 확실하지 않은 색을 찍으면 「그 색 따라가세요」가
   * 틀린 안내가 되니, 그럴 때는 색 없이 이름만 쓴다.
   */
  lineLabel?: string;
  /** 그 역·항구에서 장소까지 (도보 5분 / 버스 20분 / 바로 앞) */
  leg?: string;
}

/**
 * 일본이라서 미리 알아야 하는 것 — 맛집에서 특히 자주 걸린다.
 *
 * 사진·평점·리뷰 수는 구글맵과 트리플이 훨씬 잘한다. 거기서 이기려 들 필요가 없다.
 * 대신 그쪽이 잘 안 알려주는 게 있다 — **한국인이 실제로 헛걸음하는 이유**다:
 * 정기휴일에 문이 닫혀 있고, 카드가 안 되고, 점심때 줄이 길고, 예약이 없으면
 * 못 들어간다. 이 넷이 여행 하루를 통째로 망친다.
 *
 * 모르는 항목은 비운다. 「아마 될 것」을 적어 두면 그걸 믿고 갔다가 더 크게
 * 헛걸음한다.
 */
export interface LocalCaveat {
  /** 카드가 안 되는 곳 */
  cashOnly?: boolean;
  /** 문 여는 시간 */
  hours?: string;
  /** 정기휴일 */
  closed?: string;
  /** 줄 서는 정도와 피하는 요령 */
  waiting?: string;
  /** 예약이 필요한지 */
  reservation?: string;
  /**
   * 여기 적힌 시간이 **공식 시간표가 아니라 대체로 그렇다는 이야기**인가.
   *
   * ## 왜 필요한가
   *
   * 상점가·포장마차 거리·골목에는 **정해진 시간표가 존재하지 않는다.**
   * 아메요코도 니시키 시장도 공식 사이트가 「가게마다 다릅니다」라고만
   * 적어 둔다. 그러니 「대체로 오후 6시 전후로 닫아요」는 우리가 확인을
   * 안 한 값이 아니라, **확인할 원본 자체가 없는 값**이다.
   *
   * 그 둘을 화면이 구분하지 못하고 있었다. 확인 날짜가 없으면 무조건
   * 「언제 확인한 값인지 기록이 없어요」가 떴는데, 그건 이런 곳에서는
   * 틀린 말이다 — 우리가 게을렀다는 뜻으로 읽히고, 사용자는 어딘가에
   * 정확한 시간표가 있는데 우리가 안 봤다고 생각한다.
   *
   * 이 값이 참이면 화면이 「원래 정해진 시간표가 없다」고 밝힌다. 그러면
   * 사용자는 **구글맵에서 가게 하나를 찍어 보는 쪽**으로 바로 간다.
   *
   * ## 이걸 켜면 확인 날짜를 안 묻는다
   *
   * `checkedAt` 은 원본과 대조한 날이다. 대조할 원본이 없으면 그 날짜도
   * 있을 수 없다. 그래서 `audit:data` 는 이 값이 있는 곳을 재확인 목록에
   * 넣지 않는다 — 넣어 봐야 매달 「할 수 없는 일」이 목록에 남는다.
   *
   * **개별 가게에는 쓰지 않는다.** 가게는 시간표가 있고 우리가 아직 안 본
   * 것뿐이다. 거리·시장·골목처럼 **여러 가게의 평균**을 말하고 있을 때만.
   */
  approx?: true;
}

export interface Access extends Route {
  /**
   * 이 역 말고 다른 길.
   *
   * `Route` 와 같은 형식이라 주 경로와 **똑같이** 그려진다 — 노선 색 점도,
   * 역 이름의 일본어 원문도 붙는다. 산문으로 적으면 그게 다 빠진다.
   */
  alt?: Route;
  /**
   * 역으로 표현할 수 없는 단서.
   *
   * 「하카타에서 공항선 지하철이 그대로 이어져서 갈아타지 않아도 돼요」처럼
   * 특정 역이 아니라 이동 방식 자체에 대한 이야기만 여기 남긴다. 역이 있는
   * 대안은 `alt` 로 옮겨야 색과 원문이 붙는다.
   */
  note?: string;
}

/**
 * 거점 도시에서 당일치기로 다녀오는 근교 여행지.
 *
 * `cityId` 하나로는 표현이 안 돼서 따로 뺐다. 나라는 오사카에서도 교토에서도
 * 40분대라 어느 한쪽에만 달아두면 다른 쪽 여행자는 아예 보지 못한다.
 * 그래서 `from` 을 배열로 두고, 거점 도시를 고른 사용자에게 모두 노출한다.
 *
 * `travel` 은 편도 기준이다. 근교는 "갈 만한가"를 이동 시간으로 판단하는데,
 * 왕복이 애매하게 섞이면 하루 일정을 잘못 짜게 된다.
 */
export interface DayTrip {
  /** 여기로 당일치기 가는 거점 도시들 (data/cities.ts 의 City id) */
  from: string[];
  /** 거점 도시 중심역에서 걸리는 편도 이동 시간 */
  travel: string;
}

export interface Place {
  id: string;
  name: string;
  nameJa: string;
  category: PlaceCategory;
  /** 표시용 도시명 */
  city: string;
  /**
   * data/cities.ts 의 City id.
   *
   * 근교 여행지는 실제 행정구역이 아니라 **가장 대표적인 출발 거점**을 넣는다.
   * (예: 나라는 `osaka`) 목록·필터가 전부 이 값을 기준으로 돌아가고,
   * 나머지 출발 거점은 `dayTrip.from` 이 처리한다.
   */
  cityId: string;
  /** 지진 정보 매칭용 도도부현 (P2PQuake pref 표기와 동일) */
  prefecture: string;
  lat: number;
  lng: number;
  /**
   * 방문 인증 반경(m). 없으면 기본 10m.
   *
   * 좌표는 부지의 한 점일 뿐인데 시장·공원·신사는 수백 m에 걸쳐 있다.
   * 그런 곳에 10m를 적용하면 부지 한복판에 서 있어도 인증에 실패한다.
   */
  radiusM?: number;
  summary: string;
  /** 어떻게 가는지 — 관광지 정보와 교통 정보를 잇는 고리다 */
  access?: Access;
  /**
   * 둘러보는 데 걸리는 시간 — **추정치다.**
   *
   * 방문자 통계나 실측이 아니다. 그 장소에 뭐가 있는지를 보고 "이 정도면
   * 한 바퀴 돈다"고 판단해 넣은 값이다. 사람에 따라 크게 갈린다 — 캐널시티는
   * 쇼핑을 안 하면 1시간, 분수쇼와 라멘 스타디움까지 보면 3시간을 넘긴다.
   *
   * 그래서 화면에서도 **확정된 수치처럼 보이지 않게** 해야 한다. 입장료·역
   * 이름은 확인된 사실이지만 이 값은 눈금이라, 같은 무게로 나란히 두면
   * 사용자가 일정을 이 숫자에 맞춰 짜게 된다. (app/place/[id].tsx 참고)
   */
  duration?: string;
  /** 입장료. 무료면 '무료'. 패스 포함 여부는 여기 쓰지 말고 `passes` 에 넣는다 */
  admission?: string;
  /**
   * 위 `admission` 의 **유료 부분** 금액(엔). 무료인 곳은 넣지 않는다.
   *
   * 문자열을 파싱하지 않고 따로 둔다 — 「공원 무료 · 천수각 600엔」,
   * 「무료 (전시관 300엔)」, 「변동제 (약 8,600~10,900엔)」처럼 형식이 제각각이라
   * 정규식으로 뽑으면 조용히 틀린 값이 나온다. 사람이 읽는 문장과 계산에 쓰는
   * 숫자는 쓰임이 다르니 각자 둔다.
   *
   * 여기 값이 있다고 해서 **반드시 내야 하는 돈은 아니다.** 오사카성은 공원만
   * 걸으면 0원이고 천수각에 올라가야 600엔이다. 그래서 코스 합계에는 이 값을
   * 그냥 더하지 않고, 그 코스가 실제로 들어가는지(`CourseStop.pays`)를 보고
   * 더한다.
   */
  admissionYen?: number;
  /**
   * `admission` 문장이 말하는 **금액 그 자체**(엔). 화면이 원화를 붙일 때 쓴다.
   *
   * 단일이면 `[500]`, 금액대면 `[1500, 2500]`.
   *
   * ## 왜 `admissionYen` 을 안 쓰나
   *
   * 둘은 하는 일이 다르다.
   *
   *   `admissionYen` — **코스가 더하는 돈.** 그날 반드시 나가는 유료 부분이다.
   *   `priceYen`     — **화면이 원화로 바꿔 보여줄 금액.** 문장에 적힌 그 숫자다.
   *
   * 마쓰야마성이 그 차이를 보여준다. `admissionYen` 은 1040 인데(천수 520 +
   * 로프웨이 520) **문장에는 1040 이라는 숫자가 없다.** 그 값에 원화를 붙이면
   * 「약 9,100원」이 어디서 나온 숫자인지 알 수 없다.
   *
   * ## 애매하면 비운다
   *
   * 한 문장이 **여러 상품의 값**을 말할 때는 채우지 않는다 —
   * 「목욕만 700엔 · 2층 휴게실 1,300엔 · 3층 개인실 2,500엔」에 원화 하나를
   * 붙이면 어느 것의 값인지 모른다. 「무료 (전시관 300엔)」처럼 본체가 공짜인
   * 곳도 비운다. 답이 「무료」인데 유료 부분에 원화를 붙이면 돈을 내야 하는
   * 것처럼 읽힌다.
   *
   * ## 지어낸 숫자를 막는 장치
   *
   * 여기 적은 값은 **`admission` 문장 안에 실제로 있어야 한다**(`500` → 「500엔」,
   * `1500` → 「1,500엔」). `test/places.test.ts` 가 전부 대조한다. 문장을 고치고
   * 숫자를 안 고치면 시험이 잡는다.
   */
  priceYen?: [number] | [number, number];
  /** 이 장소를 커버하는 교통패스 */
  passes?: PassCoverage[];
  /** 근교 당일치기 여행지일 때만 채운다 */
  dayTrip?: DayTrip;
  /**
   * 헛걸음하지 않으려면 미리 알아야 하는 것.
   *
   * `tip` 과 나눈 이유는 성격이 달라서다. `tip` 은 읽어 두면 좋은 이야기지만
   * 이쪽은 **모르면 문 앞에서 돌아서는 정보**다. 그래서 화면에서도 훑어보게
   * 뱃지로 먼저 보여주고, 산문에 묻어두지 않는다.
   */
  local?: LocalCaveat;
  /** 한국인 여행자가 자주 놓치는 실제 팁 */
  tip?: string;
  /**
   * `local` 을 마지막으로 확인한 달 (`YYYY-MM`).
   *
   * ## 왜 장소에도 필요한가
   *
   * 패스·공항에만 있던 표시다. 그런데 **가게 정보가 그중 제일 빨리 썩는다** —
   * 요금 개정은 1년에 한 번 예고되고 오지만, 가게는 예고 없이 휴일을 바꾸고
   * 문을 닫는다.
   *
   * 이 값이 없으면 「언제 확인한 값인지」를 아무도 모르고, 그러면 틀린 값과
   * 맞는 값이 화면에서 똑같이 생겼다. 사용자는 둘을 구분할 방법이 없다.
   *
   * `local` 이 있는 곳에만 채운다. 좌표와 「무엇을 파는 곳인지」는 몇 년이 가도
   * 안 변해서 확인 날짜를 붙일 이유가 없다.
   */
  checkedAt?: string;
  /**
   * 그때 무엇을 보고 확인했나 — 원본 주소.
   *
   * ## 왜 날짜만으로는 모자란가
   *
   * `checkedAt` 은 「다시 볼 때가 됐다」까지만 말해 준다. 정작 다시 보려고
   * 앉으면 **원본을 처음부터 다시 찾아야 한다.** 실제로 그게 이 일의 대부분을
   * 차지한다 — 공식 페이지 주소는 개편 때마다 바뀌어서, 반년 전에 봤던
   * 주소가 404 인 경우가 흔하다(메이지 신궁·삿포로 맥주 박물관·아카렌가가
   * 그랬다).
   *
   * 주소를 남겨 두면 다음 사람은 **열어서 대조만** 하면 된다. 그 주소가
   * 404 라도 소득이다 — 사이트가 개편됐다는 뜻이고, 그건 값도 함께 바뀌었을
   * 가능성이 높다는 신호다.
   *
   * `npm run audit:data` 가 낡은 항목을 알릴 때 이 주소를 함께 찍는다.
   *
   * ## 무엇을 적나
   *
   * **그 값이 실제로 적혀 있던 페이지**다. 홈페이지 최상단이 아니라
   * 「영업안내」처럼 값이 있는 자리를 가리킨다. 여러 곳을 봤으면 결정적인
   * 한 곳만 남긴다 — 목록이 되면 아무도 안 연다.
   *
   * 원본이 없는 곳(상점가·골목처럼 공식 시간표가 존재하지 않는 곳)에는
   * `checkedAt` 자체를 두지 않으므로 이 값도 없다.
   */
  checkedVia?: string;
  /**
   * OpenStreetMap 노드·웨이 id (`node/123`, `way/456`).
   *
   * `scripts/audit-places.mjs` 가 이걸로 원본을 다시 조회해서 **폐업·이전·
   * 영업시간 변경**을 잡아낸다. 이름으로 찾으면 같은 이름의 다른 지점이
   * 잡혀서, 조용히 엉뚱한 곳과 대조하게 된다.
   *
   * 없으면 그 장소는 자동 대조에서 빠진다 — 시장·거리처럼 OSM 에 한 점으로
   * 있지 않은 곳이 그렇다.
   */
  osmId?: string;
}

