import { Place } from '@/data/places';

/**
 * 구글맵으로 보내는 링크.
 *
 * ## 왜 정보를 가져오지 않고 링크만 거는가
 *
 * 사진·평점·**지금 영업 중인지**는 구글맵이 압도적으로 잘한다. 그런데 그걸
 * 이 앱 안으로 가져오는 건 못 한다.
 *
 *   · 스크래핑은 약관 위반이다.
 *   · 정식 통로인 Places API 는 **받아온 값을 저장해 두는 걸 금지**한다
 *     (장소 id 를 뺀 나머지는 30일 초과 캐싱 불가). 영업시간을 `.ts` 에 박아
 *     정적으로 내보내는 이 앱의 구조와 정면으로 어긋난다.
 *   · 호출마다 과금되고, 키를 두려면 서버를 반드시 거쳐야 한다. 이 앱은
 *     서버 없이도 도는 게 전제다.
 *
 * 그래서 **가져오는 대신 보낸다.** 우리가 가진 정적 데이터는 언젠가 낡는데,
 * 링크 너머의 값은 항상 최신이다. 비용도 약관 문제도 없다.
 *
 * ## 왜 좌표가 아니라 이름으로 보내나
 *
 * 좌표로 보내면 지도의 그 지점에 핀만 꽂힌다. 우리가 정작 보내고 싶은 건
 * **가게 정보 화면**이다 — 거기에 오늘 영업시간과 최근 사진이 있다.
 *
 * 이름은 간판 표기(`nameJa`)를 쓴다. 한글 표기는 구글맵 일본 데이터에 없는
 * 경우가 많아서 엉뚱한 곳이 잡힌다.
 */
export function mapsUrl(place: Place): string {
  const query = place.nameJa || place.name;
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`;
}

/**
 * 「2026년 8월에 확인했어요」.
 *
 * 확인한 때를 밝히는 게 왜 중요하냐면, **틀린 값과 맞는 값이 화면에서 똑같이
 * 생겼기** 때문이다. 날짜가 없으면 사용자는 둘을 구분할 방법이 없고, 낡은
 * 영업시간을 오늘의 사실로 읽는다.
 *
 * 날짜가 붙어 있으면 「반년 전 정보네, 구글맵도 봐야겠다」로 이어진다. 그게
 * 정직한 상태다 — 우리가 최신을 보장할 수 없다는 걸 숨기지 않는 것.
 */
export function checkedLabel(checkedAt?: string): string | null {
  const m = /^(\d{4})-(\d{2})$/.exec(checkedAt ?? '');
  if (!m) return null;
  return `${m[1]}년 ${Number(m[2])}월에 확인한 정보예요`;
}
