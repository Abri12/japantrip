/**
 * 방위·지형 접미사.
 *
 * 지명과 구분하는 이유는 띄어쓰기 때문이다. 「福岡県 + 福岡」처럼 지명이 이어지면
 * 사이를 띄워야 읽히지만(후쿠오카현 후쿠오카), 「大阪 + 湾」은 붙여야 한다(오사카만).
 * 접미사는 자기 앞의 공백을 값에 직접 갖고 있고, 지명끼리만 자동으로 띄운다.
 */
const SUFFIXES = new Set([
  '西方沖', '東方沖', '南方沖', '北方沖',
  '北東部', '北西部', '南東部', '南西部',
  '中越', '下越', '上越',
  '北部', '南部', '東部', '西部', '中部',
  '内陸', '沿岸', '諸島', '半島', '近海', '付近', '水道', '地方',
  '沖', '灘', '湾',
]);

/** 도도부현 키. 짧게 줄일 때 접두사로 떼어내는 대상이다. */
const PREFECTURES = new Set(
  Object.keys(DICT).filter((k) => /[県都府]$/.test(k) || k === '北海道'),
);

/** 최장 일치를 위해 길이 내림차순으로 미리 정렬한다. */
const KEYS = Object.keys(DICT).sort((a, b) => b.length - a.length);

type TokenKind = 'pref' | 'place' | 'suffix' | 'raw';
interface Token {
  text: string;
  kind: TokenKind;
}

/**
 * 지명을 토큰으로 쪼갠다.
 *
 * 문자열로 바로 합치지 않는 이유는, 화면마다 필요한 정보가 다르기 때문이다.
 * 진앙 제목에는 도도부현이면 충분하고, 긴급속보 대상지역 목록에는 오히려
 * 세부 지역이 있어야 서로 구분된다. 토큰으로 두면 둘 다 만들 수 있다.
 */
function tokenize(ja: string): Token[] {
  const tokens: Token[] = [];
  let rest = ja;

  outer: while (rest.length > 0) {
    for (const key of KEYS) {
      if (rest.startsWith(key)) {
        const kind: TokenKind = SUFFIXES.has(key)
          ? 'suffix'
          : PREFECTURES.has(key)
            ? 'pref'
            : 'place';
        tokens.push({ text: DICT[key], kind });
        rest = rest.slice(key.length);
        continue outer;
      }
    }

    const ch = rest[0];
    tokens.push({
      text: ch === '、' ? ', ' : ch === '・' ? '·' : ch,
      kind: 'raw',
    });
    rest = rest.slice(1);
  }

  return tokens;
}

/** 토큰을 이어 붙인다. 지명끼리는 띄우고, 접미사는 자기 공백을 그대로 쓴다. */
function join(tokens: Token[]): string {
  let out = '';
  let prevWasName = false;

  for (const t of tokens) {
    const isName = t.kind === 'pref' || t.kind === 'place';
    if (isName && prevWasName) out += ' ';
    out += t.text;
    prevWasName = isName;
  }

  return out.replace(/\s+/g, ' ').trim();
}

/** 「후쿠오카현」 → 「후쿠오카」. 홋카이도는 그 자체가 이름이라 두 글자를 떼지 않는다. */
function shortenPref(ko: string): string {
  if (ko === '홋카이도') return ko;
  return ko.replace(/(현|부|도)$/, '');
}

/**
 * 일본어 지명을 한국어로 옮긴다. 사전에 없는 글자는 그대로 남는다.
 * 전체를 그대로 옮기므로 가장 길다 — 화면에는 아래 두 함수를 쓴다.
 */
export function toKorean(ja: string): string {
  return join(tokenize(ja));
}

/** 한 글자라도 한글로 바뀌었는지. 안 바뀌었으면 괄호를 붙일 이유가 없다. */
function hasKorean(s: string): boolean {
  return /[가-힣]/.test(s);
}

/**
 * 진앙 이름을 짧게 줄인다.
 *
 * 「熊本県天草・芦北地方」을 그대로 옮기면 "구마모토현 아마쿠사·아시키타 지방"이 되는데,
 * 여행자에게 필요한 건 **어느 지역인가**지 행정 단위가 아니다. 그래서
 *
 * - 「지방」을 뗀다 (정보가 없다)
 * - 도도부현의 「현·부·도」를 뗀다 (구마모토현 → 구마모토)
 * - 도도부현이 있으면 그 아래 세부 지역은 뺀다
 * - 방위·지형(북부, 앞바다, 근해)은 남긴다 — 위치 감각에 직결된다
 *
 * 정확한 원문은 괄호에 남으므로 정보가 사라지지는 않는다.
 */
function shortName(ja: string): string {
  const tokens = tokenize(ja).filter((t) => t.text !== ' 지방');
  const pref = tokens.find((t) => t.kind === 'pref');

  // 도도부현이 있으면 그것만 쓰고 세부 지역은 버린다
  const kept = pref
    ? tokens.filter((t) => t.kind !== 'place' && t.text !== '·')
    : tokens;

  const out = join(
    kept.map((t) => (t.kind === 'pref' ? { ...t, text: shortenPref(t.text) } : t)),
  );

  return out || join(tokens);
}

/**
 * 화면에 쓰는 표기: `짧은 한국어 (원문)`.
 *
 * 옮길 수 있는 게 하나도 없으면 원문만 반환한다 — "日本語 (日本語)" 처럼
 * 같은 글자를 두 번 보여주지 않기 위해서다.
 */
export function regionLabel(ja: string): string {
  if (!ja) return '';
  const ko = shortName(ja);
  if (!hasKorean(ko) || ko === ja) return ja;
  return `${ko} (${ja})`;
}

/**
 * 긴급지진속보 대상지역 목록용.
 *
 * 여기서는 반대로 **세부 지역을 남긴다.** 같은 현 안의 여러 지역이 나란히 오는
 * 경우가 많아서(구마모토현 구마모토 / 구마모토현 아마쿠사·아시키타 / 구마모토현 구마),
 * 도도부현만 남기면 "구마모토, 구마모토, 구마모토"가 되어 버린다.
 * 대신 앞에 붙는 도도부현을 떼어 짧게 만든다.
 */
export function areaLabel(ja: string): string {
  if (!ja) return '';
  const tokens = tokenize(ja).filter((t) => t.text !== ' 지방');
  const places = tokens.filter((t) => t.kind !== 'pref');
  const hasPlace = places.some((t) => t.kind === 'place');

  const out = join(
    hasPlace
      ? places
      : tokens.map((t) => (t.kind === 'pref' ? { ...t, text: shortenPref(t.text) } : t)),
  );

  return hasKorean(out) ? out : ja;
}

/** 자리가 좁은 곳에서 쓰는 짧은 한국어 표기 (괄호 없음). */
export function regionKorean(ja: string): string {
  if (!ja) return '';
  const ko = shortName(ja);
  return hasKorean(ko) ? ko : ja;
}
