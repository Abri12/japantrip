import { Place } from '@/data/places';

/**
 * 목록에 보일 값 — **한 덩어리로 줄인다.**
 *
 * ## 왜 줄이나
 *
 * `admission` 은 문장이다. 「공원 무료 · 천수각 1,200엔」, 「변동제 (약
 * 8,400~11,900엔)」. 상세 화면에서는 그 문장이 정확히 필요한 정보지만,
 * 목록에서는 **줄 하나를 세 줄로 만드는 원인**이 된다. 오른쪽이 세 줄이 되면
 * 왼쪽 장소 이름과 역 이름까지 밀려서 같이 쪼개진다.
 *
 * 목록에서 값이 하는 일은 「얼마쯤 드나」를 눈으로 훑게 하는 것 하나다.
 * 정확한 조건은 열어 보면 있다 — `lib/access.ts` 가 역 이름의 일본어 원문을
 * 상세로 넘긴 것과 같은 이유다.
 *
 * ## 왜 큰 쪽인가
 *
 * `priceYen` 이 있으면 그 값을 쓴다. 문장의 앞부분을 잘라 쓰는 방법도 있었는데
 * (「공원 무료 · 천수각 1,200엔」 → 「공원 무료」), **그러면 싸 보이는 쪽으로
 * 틀린다.** 이 앱은 반대 방향으로만 틀리기로 했다 — 값을 모르는 곳을 0 으로
 * 세지 않는 것과 같은 규칙이다(`lib/budget.ts`).
 *
 * 「공원 무료 · 천수각 1,200엔」을 목록에서 「1,200엔」으로 보고 들어온 사람은
 * 공원이 무료라는 걸 상세에서 알게 된다. 반대로 「공원 무료」로 보고 갔다가
 * 천수각 앞에서 1,200엔을 만나는 것보다 낫다.
 *
 * ## 줄일 수 없는 것
 *
 * `priceYen` 이 없는 곳이 스물넷 있다. 「커피 600엔대 · 아침 세트 1,500엔
 * 안팎」처럼 **하나의 숫자로 줄일 수 없는 값**이라 일부러 안 넣은 것이다.
 * 그건 문장을 그대로 주고, 화면이 두 줄에서 자른다. 억지로 대표값을 만드는
 * 것보다 잘린 문장이 정직하다.
 */
export function shortPrice(place: Place): string | undefined {
  const p = place.priceYen;
  if (p) {
    const [low, high] = p;
    return high === undefined ? `${yen(low)}엔` : `${yen(low)}~${yen(high)}엔`;
  }

  const adm = place.admission;
  if (!adm) return undefined;

  /* 「무료 (전시관 300엔)」처럼 괄호로 덧붙인 단서는 목록에서 뗀다. 괄호는
     본값이 아니라 설명이라, 떼어도 앞의 값이 말하는 바가 달라지지 않는다. */
  const bare = adm.replace(/\s*\([^)]*\)\s*$/, '').trim();
  return bare || adm;
}

function yen(n: number): string {
  return n.toLocaleString('en-US');
}
